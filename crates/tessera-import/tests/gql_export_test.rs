use tessera_graph::{Graph, Property};
use tessera_import::gql_export::export_gql;

fn empty_graph() -> Graph {
    Graph::new()
}

#[test]
fn export_gql_empty_graph_has_header_comment() {
    let g = empty_graph();
    let out = export_gql(&g).unwrap();
    assert!(
        out.contains("// Generated by TesseraGraph Export"),
        "got: {out}"
    );
}

#[test]
fn export_gql_empty_graph_has_edge_limitation_comment() {
    let g = empty_graph();
    let out = export_gql(&g).unwrap();
    assert!(
        out.contains("// NOTE: Edge export is not yet supported."),
        "got: {out}"
    );
}

#[test]
fn export_gql_single_node_create_statement() {
    let mut g = empty_graph();
    let props: tessera_graph::Properties =
        std::iter::once(("name".to_owned(), Property::String("Alice".to_owned()))).collect();
    g.add_node("Person", props).unwrap();
    let out = export_gql(&g).unwrap();
    assert!(out.contains("CREATE (:Person"), "got: {out}");
    assert!(out.contains("name: 'Alice'"), "got: {out}");
}

#[test]
fn export_gql_node_without_props_no_braces() {
    let mut g = empty_graph();
    g.add_node("Empty", tessera_graph::Properties::new())
        .unwrap();
    let out = export_gql(&g).unwrap();
    assert!(out.contains("CREATE (:Empty)"), "got: {out}");
}

#[test]
