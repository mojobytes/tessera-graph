#[test]
fn export_gql_properties_sorted_alphabetically() {
    let mut g = empty_graph();
    let props: tessera_graph::Properties = [
        ("zzz".to_owned(), Property::I64(1)),
        ("aaa".to_owned(), Property::I64(2)),
    ]
    .into_iter()
    .collect();
    g.add_node("Node", props).unwrap();
    let out = export_gql(&g).unwrap();
    let aaa_pos = out.find("aaa").unwrap();
    let zzz_pos = out.find("zzz").unwrap();
    assert!(aaa_pos < zzz_pos, "props not sorted; got: {out}");
}

#[test]
fn export_gql_string_with_single_quote_escaped() {
    let mut g = empty_graph();
    let props: tessera_graph::Properties =
        std::iter::once(("name".to_owned(), Property::String("O'Brien".to_owned()))).collect();
    g.add_node("Person", props).unwrap();
    let out = export_gql(&g).unwrap();
    // The apostrophe should be escaped as \'
    assert!(out.contains("\\'"), "apostrophe not escaped; got: {out}");
}
